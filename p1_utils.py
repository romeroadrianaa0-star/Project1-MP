def make_splits(img_id, is_test, val_frac=0.1, seed=0):
    """Test = VOC val. Validation = all crops of a random 10% of the training images, so no photo is on both sides."""
    rng = np.random.default_rng(seed)
    train_imgs = np.unique(img_id[~is_test])
    val_imgs = set(rng.choice(train_imgs, int(len(train_imgs) * val_frac), replace=False))
    in_val = np.array([i in val_imgs for i in img_id]) & ~is_test
    idx_test = np.where(is_test)[0]
    idx_val = np.where(in_val)[0]
    idx_train = np.where(~is_test & ~in_val)[0]
    assert not set(img_id[idx_train]) & set(img_id[idx_val]), 'an image is on both sides'
    return idx_train, idx_val, idx_test


def crop_counts(y, splits):
    """Crops per class in each split: the handout asks you to report this table."""
    counts = np.stack([np.bincount(y[i], minlength=len(CLASSES)) for i in splits], 1)
    print(f"{'class':12s} {'train':>6s} {'val':>5s} {'test':>5s}")
    for c, (a, b, t) in zip(CLASSES, counts):
        print(f'{c:12s} {a:6d} {b:5d} {t:5d}')
    print(f"{'total':12s} {counts[:, 0].sum():6d} {counts[:, 1].sum():5d} {counts[:, 2].sum():5d}")
    return counts


# ------------------------------------------------------------------------------------------------------- photos
PHOTO_EXT = ('.jpg', '.jpeg', '.png', '.heic', '.heif')


def read_upright(path):
    """The photo as your phone shows it: the EXIF orientation flag is applied."""
    return np.asarray(ImageOps.exif_transpose(Image.open(path)).convert('RGB'))


def center_square(a):
    h, w = a.shape[:2]; s = min(h, w)
    return a[(h - s) // 2:(h - s) // 2 + s, (w - s) // 2:(w - s) // 2 + s]


def load_photo(path, size):
    """Upright, largest center square, resized like the VOC crops."""
    return cv2.resize(center_square(read_upright(path)), (size, size), interpolation=cv2.INTER_AREA)


def rotate_photo(path, deg, size):
    """The photo's center square, rotated counterclockwise by deg about its center at the same scale, then resized.
    90 and 180 degrees are exact; other angles use bilinear interpolation and fill the corners by replicating the border."""
    a = center_square(read_upright(path))
    if deg % 90 == 0:
        r = np.rot90(a, (deg // 90) % 4)
    else:
        s = a.shape[0]
        M = cv2.getRotationMatrix2D((s / 2, s / 2), deg, 1.0)
        r = cv2.warpAffine(a, M, (s, s), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REPLICATE)
    return cv2.resize(np.ascontiguousarray(r), (size, size), interpolation=cv2.INTER_AREA)


def photo_files(folder):
    return sorted(p for p in glob.glob(os.path.join(folder, '*')) if p.lower().endswith(PHOTO_EXT))


def load_photo_folder(folder, size):
    """folder/<class>/*.jpg -> X (N, size, size, 3) uint8, y (N,) class index, paths."""
    X, Y, P = [], [], []
    for c, name in enumerate(CLASSES):
        for p in photo_files(os.path.join(folder, name)):
            X.append(load_photo(p, size)); Y.append(c); P.append(p)
    return (np.stack(X) if X else np.zeros((0, size, size, 3), np.uint8)), np.array(Y, int), P


# ----------------------------------------------------------------------------------------------------------- B3
B3_FACTORS = {                    # factor: its conditions; the first one is the shared baseline photo
    'rotation': ['0', '30', '90', '180'],
    'occlusion': ['none', 'quarter', 'half'],
    'viewpoint': ['front', 'side', 'top', 'below'],
    'lighting': ['normal', 'dim', 'backlit'],
    'distance': ['near', 'far']}
REQUIRED_FACTORS = ['rotation', 'occlusion']
CHOOSABLE_FACTORS = ['viewpoint', 'lighting', 'distance']
B3_MODELS = ['A2', 'A4', 'A6-H', 'A6-frozen']        # A6-frozen: the 665 extension, rotation only
CSV_B3_COLUMNS = ['object', 'class', 'factor', 'condition', 'model', 'pred', 'correct']


def load_b3_series(folder, size, chosen):
    """folder/<class>/<object>/{baseline, occlusion_quarter, occlusion_half, <chosen>_<condition>}.jpg
    -> records with class, object, factor, condition, image. Rotations are made in code from the baseline."""
    assert chosen in CHOOSABLE_FACTORS, f'chosen must be one of {CHOOSABLE_FACTORS}'
    recs, missing = [], []
    for c, name in enumerate(CLASSES):
        for obj_dir in sorted(d for d in glob.glob(os.path.join(folder, name, '*')) if os.path.isdir(d)):
            files = {os.path.splitext(os.path.basename(p))[0]: p for p in photo_files(obj_dir)}
            if 'baseline' not in files:
                missing.append(os.path.join(obj_dir, 'baseline')); continue
            for factor in REQUIRED_FACTORS + [chosen]:
                for k, cond in enumerate(B3_FACTORS[factor]):
                    if k == 0:
                        img = load_photo(files['baseline'], size)
                    elif factor == 'rotation':
                        img = rotate_photo(files['baseline'], int(cond), size)
                    elif f'{factor}_{cond}' in files:
                        img = load_photo(files[f'{factor}_{cond}'], size)
                    else:
                        missing.append(os.path.join(obj_dir, f'{factor}_{cond}')); continue
                    recs.append(dict(cls=c, object=f'{name}/{os.path.basename(obj_dir)}', factor=factor,
                                     condition=cond, image=img))
    if missing:
        print(f'{len(missing)} photos missing, for example', missing[:3])
    return recs


def b3_unique(recs):
    """The B3 records with each photo once. load_b3_series repeats the baseline photo as the first condition of every
    factor (rotation 0, occlusion none, and your factor's first condition); this keeps rotation's copy only."""
    return [r for r in recs if r['condition'] != B3_FACTORS[r['factor']][0] or r['factor'] == 'rotation']


def b3_rows(recs, model, probs):
    """probs: (N, 19) class probabilities of one model, in the order of recs."""
    probs = np.asarray(probs)
    assert model in B3_MODELS and probs.shape == (len(recs), len(CLASSES)), (model, probs.shape)
    return [dict(object=r['object'], **{'class': CLASSES[r['cls']]}, factor=r['factor'], condition=r['condition'],
                 model=model, pred=CLASSES[int(p.argmax())], correct=int(p.argmax() == r['cls']))
            for r, p in zip(recs, probs)]


def write_b3_csv(rows, path):
    """Writes rows to path. Rows already in the file for OTHER models are kept, so P1_B (A2, A4, A6-H) and
    P1_665 (A6-frozen) can each write their own models in either order; rewriting a model replaces its rows."""
    for r in rows:
        assert set(r) == set(CSV_B3_COLUMNS), sorted(r)
        assert r['model'] in B3_MODELS and r['class'] in CLASSES and r['pred'] in CLASSES
        assert r['condition'] in B3_FACTORS[r['factor']], (r['factor'], r['condition'])
    models, kept = {r['model'] for r in rows}, []
    if os.path.exists(path):
        with open(path, newline='') as f:
            kept = [r for r in csv.DictReader(f) if r['model'] not in models]
    with open(path, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=CSV_B3_COLUMNS); w.writeheader(); w.writerows(kept + rows)
    print(f'wrote {len(rows)} rows to {path}' + (f', and kept {len(kept)} rows of other models' if kept else ''))


# ----------------------------------------------------------------------------------------------------------- B5
B5_MODELS = ['A6-H', 'A6-H-repaired']
CSV_B5_COLUMNS = ['object', 'class', 'condition', 'model', 'pred', 'correct']


def load_b5_adapt(folder, size, factor, condition):
    """folder/<class>/*.jpg. For rotation, photograph ordinarily: the rotation is made here."""
    X, y, P = load_photo_folder(folder, size)
    if factor == 'rotation' and P:
        X = np.stack([rotate_photo(p, int(condition), size) for p in P])
    return X, y, P


def load_b5_heldout(folder, size, factor, condition):
    """folder/<class>/ordinary.jpg and challenge.jpg (for rotation, only ordinary.jpg: the rotation is made here).
    Records with class, object, condition ('ordinary' or '<factor>_<condition>'), image."""
    recs = []
    for c, name in enumerate(CLASSES):
        d = os.path.join(folder, name)
        files = {os.path.splitext(os.path.basename(p))[0]: p for p in photo_files(d)}
        if 'ordinary' not in files:
            continue
        recs.append(dict(cls=c, object=f'{name}/heldout', condition='ordinary', image=load_photo(files['ordinary'], size)))
        if factor == 'rotation':
            img = rotate_photo(files['ordinary'], int(condition), size)
        else:
            assert 'challenge' in files, f'{d}: no challenge photo'
            img = load_photo(files['challenge'], size)
        recs.append(dict(cls=c, object=f'{name}/heldout', condition=f'{factor}_{condition}', image=img))
    return recs


def check_photos(classes, chosen, b5_factor=None, root=None):
    """Counts your photos against the handout, prints anything missing, and returns True if nothing is.
    classes: your five class names. chosen: your third B3 factor. b5_factor: the repaired factor, once you know it.
    B1: 10 photos per class, named <object>_<n>.jpg, of at least 3 objects. B3: 2 objects per class (folders named by
    object), each with every photo of its series. B5 (once the folder exists): 2 adaptation photos per class, named
    <object>.jpg and not B3 objects, and a held-out ordinary.jpg (plus challenge.jpg unless rotation)."""
    root = root or PHOTO_DIR
    assert chosen in CHOOSABLE_FACTORS, f'chosen must be one of {CHOOSABLE_FACTORS}'
    names = lambda d: {os.path.splitext(os.path.basename(p))[0] for p in photo_files(d)}
    series = ['baseline', 'occlusion_quarter', 'occlusion_half'] + [f'{chosen}_{c}' for c in B3_FACTORS[chosen][1:]]
    problems = []
    for name in classes:
        assert name in CLASSES, f'{name} is not a VOC class name'
        b1 = names(os.path.join(root, 'B1', name))
        if len(b1) != 10:
            problems.append(f'B1/{name}: {len(b1)} photos, expected 10')
        b1_objects = {n.rsplit('_', 1)[0] if n.rsplit('_', 1)[-1].isdigit() else n for n in b1}
        if b1 and len(b1_objects) < 3:
            problems.append(f'B1/{name}: {len(b1_objects)} object names ({", ".join(sorted(b1_objects))}), expected 3 or more')
        objs = sorted(d for d in glob.glob(os.path.join(root, 'B3', name, '*')) if os.path.isdir(d))
        if len(objs) != 2:
            problems.append(f'B3/{name}: {len(objs)} objects, expected 2')
        for d in objs:
            miss = [f for f in series if f not in names(d)]
            if miss:
                problems.append(f'B3/{name}/{os.path.basename(d)}: missing {", ".join(miss)}')
        if os.path.isdir(os.path.join(root, 'B5')):
            adapt = names(os.path.join(root, 'B5', 'adapt', name))
            if len(adapt) != 2:
                problems.append(f'B5/adapt/{name}: {len(adapt)} photos, expected 2')
            reused = adapt & {os.path.basename(d) for d in objs}
            if reused:
                problems.append(f'B5/adapt/{name}: {", ".join(sorted(reused))} is a B3 object')
            want = ['ordinary'] + ([] if b5_factor in (None, 'rotation') else ['challenge'])
            miss = [f for f in want if f not in names(os.path.join(root, 'B5', 'heldout', name))]
            if miss:
                problems.append(f'B5/heldout/{name}: missing {", ".join(miss)}')
    print('photos complete' if not problems else f'{len(problems)} problems:\n  ' + '\n  '.join(problems[:40]))
    return not problems


def b5_rows(recs, model, probs):
    probs = np.asarray(probs)
