def md5sum(path, chunk=1 << 22):
    h = hashlib.md5()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(chunk), b''):
            h.update(block)
    return h.hexdigest()


def get_voc():
    """Download and extract VOC 2012 trainval into VOC_PARENT, unless it is already there.
    The Oxford server is tried first, then a mirror; a copy is accepted only if its MD5 matches."""
    if os.path.isdir(os.path.join(VOC_ROOT, 'Annotations')):
        return
    tar = os.path.join(VOC_PARENT, VOC_TAR)
    if not (os.path.exists(tar) and md5sum(tar) == VOC_MD5):
        socket.setdefaulttimeout(60)
        for url in VOC_URLS:
            try:
                t0 = time.time()
                print('downloading', url)
                urllib.request.urlretrieve(url, tar)
                if md5sum(tar) == VOC_MD5:
                    print(f'  done in {time.time() - t0:.0f} s, checksum OK')
                    break
                print('  checksum mismatch; trying the next source')
            except Exception as e:
                print('  failed:', e)
        else:
            raise RuntimeError('Could not download VOC 2012. Try again later, or ask on Piazza.')
    t0 = time.time()
    with tarfile.open(tar) as t:
        t.extractall(VOC_PARENT)
    os.remove(tar)
    print(f'extracted in {time.time() - t0:.0f} s')


def square_crop(img, x1, y1, x2, y2, size):
    cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
    side = int(round(max(x2 - x1, y2 - y1)))
    a, b = int(round(cx - side / 2)), int(round(cy - side / 2))
    big = cv2.copyMakeBorder(img, side, side, side, side, cv2.BORDER_REPLICATE)
    out = big[b + side:b + 2 * side, a + side:a + 2 * side]
    return cv2.resize(out, (size, size), interpolation=cv2.INTER_AREA)


def voc_objects(min_side=32):
    """Every kept box: (image id, class index, box x1 y1 x2 y2, is_test, person boxes in that image).
    Person boxes and boxes marked difficult or under min_side px are skipped. VOC val is the project's test set."""
    objs = []
    for split in ['train', 'val']:
        for iid in open(os.path.join(VOC_ROOT, 'ImageSets', 'Main', f'{split}.txt')).read().split():
            root = ET.parse(os.path.join(VOC_ROOT, 'Annotations', f'{iid}.xml')).getroot()
            people = [tuple(float(o.find('bndbox').find(k).text) for k in ('xmin', 'ymin', 'xmax', 'ymax'))
                      for o in root.findall('object') if o.find('name').text.strip() == 'person']
            for obj in root.findall('object'):
                name = obj.find('name').text.strip()
                diff = obj.find('difficult')
                if name == 'person' or (diff is not None and diff.text.strip() == '1'):
                    continue
                bb = obj.find('bndbox')
                x1, y1, x2, y2 = [float(bb.find(k).text) for k in ('xmin', 'ymin', 'xmax', 'ymax')]
                if x2 - x1 < min_side or y2 - y1 < min_side:
                    continue
                objs.append((iid, CLASSES.index(name), (x1 - 1, y1 - 1, x2, y2), split == 'val', people))   # 1-based boxes
    return objs


def overlaps_person(box, people, frac=0.1):
    """True if at least frac of some person's box falls inside this object's square crop."""
    x1, y1, x2, y2 = box
    side, cx, cy = max(x2 - x1, y2 - y1), (x1 + x2) / 2, (y1 + y2) / 2
    sx1, sy1, sx2, sy2 = cx - side / 2, cy - side / 2, cx + side / 2, cy + side / 2
    for px1, py1, px2, py2 in people:
        iw, ih = min(sx2, px2) - max(sx1, px1), min(sy2, py2) - max(sy1, py1)
        if iw > 0 and ih > 0 and iw * ih >= frac * (px2 - px1) * (py2 - py1):
            return True
    return False


def build_crops(size):
    """X (N, size, size, 3) uint8 RGB, y (N,) class index, img_id (N,), is_test (N,), has_person (N,).
    Each crop is the square of side max(w, h) centered on the box, padded by replicating the border, then resized."""
    get_voc()
    X, y, img_id, is_test, has_person = [], [], [], [], []
    cur, img = None, None
    for iid, c, box, test, people in voc_objects():
        if iid != cur:
            cur = iid
            img = cv2.cvtColor(cv2.imread(os.path.join(VOC_ROOT, 'JPEGImages', f'{iid}.jpg')), cv2.COLOR_BGR2RGB)
        X.append(square_crop(img, *box, size)); y.append(c); img_id.append(iid); is_test.append(test)
        has_person.append(overlaps_person(box, people))
    return np.stack(X), np.array(y), np.array(img_id), np.array(is_test), np.array(has_person)


def load_crops(size):
    """X, y, img_id, is_test. Built once (VOC is downloaded if needed) and cached in DATA_DIR:
    64 px is 0.2 GB, 224 px is 2.5 GB. Crops of every size come in the same order."""
    path = os.path.join(DATA_DIR, f'voc_crops{size}.npz')
    if os.path.exists(path) and 'has_person' not in np.load(path).files:
        os.remove(path)                                   # a cache from an older version: rebuild it
    if not os.path.exists(path):
        t0 = time.time()
        X, y, img_id, is_test, has_person = build_crops(size)
        np.savez(path, X=X, y=y, img_id=img_id, is_test=is_test, has_person=has_person)
        print(f'built {len(X)} crops of {size} px in {time.time() - t0:.0f} s')
    d = np.load(path)
    return d['X'], d['y'], d['img_id'], d['is_test']


