def selftest():
    """A fake sideways phone photo (EXIF orientation 6): checks orientation, exact rotation, the B3 loader and CSV."""
    tmp = os.path.join(ROOT, '_selftest')
    shutil.rmtree(tmp, ignore_errors=True)
    rng = np.random.default_rng(0)
    up = (rng.random((300, 400, 3)) * 255).astype(np.uint8)
    up[100:200, 150:250] = [255, 0, 0]
    raw = Image.fromarray(np.ascontiguousarray(np.rot90(up, 1)))              # stored sideways, as a phone does
    exif = Image.Exif(); exif[0x0112] = 6                                     # "rotate 90 degrees clockwise to view"
    obj = os.path.join(tmp, 'B3', 'bottle', 'obj1'); os.makedirs(obj)
    raw.save(os.path.join(obj, 'baseline.png'), exif=exif)
    for name in ('occlusion_quarter', 'occlusion_half', 'lighting_dim', 'lighting_backlit'):
        Image.fromarray(up).save(os.path.join(obj, name + '.png'))
    a = read_upright(os.path.join(obj, 'baseline.png'))
