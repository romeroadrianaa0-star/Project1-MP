def shrink_photos(src=None, dst=None, long_side=1024):
    """Copy PHOTO_DIR with every photo upright and its longest side at 1024 px, keeping the folder layout."""
    src = src or PHOTO_DIR
    dst = dst or os.path.join(ROOT, 'photos_small')
    n = 0
    for p in glob.glob(os.path.join(src, '**', '*'), recursive=True):
        if not p.lower().endswith(PHOTO_EXT):
            continue
        img = ImageOps.exif_transpose(Image.open(p)).convert('RGB')
        img.thumbnail((long_side, long_side), Image.LANCZOS)
        out = os.path.join(dst, os.path.relpath(os.path.splitext(p)[0], src) + '.jpg')
        os.makedirs(os.path.dirname(out), exist_ok=True)
        img.save(out, quality=90)
        n += 1
    size = sum(os.path.getsize(q) for q in glob.glob(os.path.join(dst, '**', '*.jpg'), recursive=True))
    print(f'{n} photos -> {dst}, {size / 1e6:.1f} MB')


