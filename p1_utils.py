    return [dict(object=r['object'], **{'class': CLASSES[r['cls']]}, condition=r['condition'], model=model,
                 pred=CLASSES[int(p.argmax())], correct=int(p.argmax() == r['cls'])) for r, p in zip(recs, probs)]


